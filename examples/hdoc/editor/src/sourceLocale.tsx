const orderedEn = Object.entries(dynamicEn).sort((a, b) => b[0].length - a[0].length)

export function localizeDynamic(locale: EditorLocale, source: string): string {
  if (locale === 'zh-CN' || !/[\u3400-\u9fff]/.test(source)) return source
  const exact = localizeSource(locale, source)
  if (exact !== source) return exact
  if (locale.startsWith('zh')) return source.replace(/[\u3400-\u9fff]/g, character => traditionalChars[character] ?? character)
  let match = /^第 (\d+) 个分片$/.exec(source)
  if (match) return `Chunk ${match[1]}`
  match = /^第 (\d+) 页$/.exec(source)
  if (match) return `Page ${match[1]}`
  match = /^revision (\d+) · 已(删除|新增|撤销)第 (\d+) (行|列)$/.exec(source)
  if (match) return `Revision ${match[1]} · ${match[2] === '删除' ? 'Deleted' : match[2] === '新增' ? 'Added' : 'Removed'} ${match[4] === '行' ? 'row' : 'column'} ${match[3]}`
  let result = source
  for (const [original, translated] of orderedEn) result = result.replaceAll(original, translated)
  return result
}

export function localizeSource(locale: EditorLocale, source: string): string {
  const value = source.trim()
  if (!value) return source
  const translated = translateChineseSource(locale, value)
    ?? (locale.startsWith('en') ? sourceEn[value] : locale === 'zh-CN' ? value : sourceTw[value])
    ?? value
  return source.replace(value, translated)
}

export function LocalText({ source }: { source: string }) {
  const { locale } = useI18n()
  return <>{localizeSource(locale, source)}</>
}
