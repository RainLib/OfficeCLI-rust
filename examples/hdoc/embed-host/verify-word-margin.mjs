import assert from 'node:assert/strict'
import { join } from 'node:path'
import { expect } from '../editor/node_modules/@playwright/test/index.mjs'

/** Runs after the native review roundtrip, against the real workbench editor. */
export async function verifyWordMargin(page, output, checks) {
  const editor = page.locator('.desk-editor.is-visible')
  const content = editor.locator('.tiptap').first()
  const viewport = editor.locator('.document-scroll.canvas-viewport:not([hidden])')
  const comments = editor.getByRole('complementary', { name: 'Word 审阅' })
  const cards = comments.locator('[data-review-card]')
  const button = (name, host = editor) => host.getByRole('button', { name, exact: true })
  const originalViewport = page.viewportSize()
  await page.setViewportSize({ width: 1800, height: 1040 })
  assert(await comments.evaluate(element => element.closest('.canvas-viewport') === element.closest('.workspace').querySelector('.document .tiptap').closest('.canvas-viewport')))
  await expect(editor.locator('.editor-layout > .workspace-sidebar[aria-label="Word 审阅"]')).toHaveCount(0)

  for (const [text, message] of [['Project Phoenix kickoff agenda', '请补充这次启动会的负责人。'], ['Stakeholder alignment', '这部分需要同步参与方。']]) {
    const paragraph = content.getByText(text, { exact: true })
    await paragraph.scrollIntoViewIfNeeded()
    await paragraph.evaluate(element => {
      element.closest('.tiptap').focus()
      const range = document.createRange()
      range.selectNodeContents(element)
      const selection = window.getSelection()
      selection.removeAllRanges(); selection.addRange(range)
      document.dispatchEvent(new Event('selectionchange'))
    })
    await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe(text)
    await button('新建批注').click()
    await comments.getByRole('textbox', { name: '批注内容' }).fill(message)
    const posted = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/word-review'))
    await button('发布批注', comments).click()
    const response = await posted
    assert(response.ok(), await response.text())
    await expect(comments.getByText(message, { exact: true })).toBeVisible()
  }
  await expect(cards).toHaveCount(3)
  await expect(comments).toHaveAttribute('data-compact', 'false')
  const first = cards.filter({ hasText: '请补充这次启动会的负责人。' })
  const second = cards.filter({ hasText: '这部分需要同步参与方。' })
  const id = await first.getAttribute('data-review-card')
  const marks = content.locator(`[data-word-comment-id="${id}"]`), mark = marks.first()
  const highlighted = () => marks.evaluateAll(elements => elements.map(element => element.textContent).join(''))
  await expect.poll(highlighted).toBe('Project Phoenix kickoff agenda')
  await expect(editor.locator('.selection-menu')).not.toBeVisible()
  await mark.click()
  await expect(first).toHaveAttribute('data-active', 'true')
  await expect(mark).toHaveClass(/is-active/)
  await button('Project Phoenix kickoff agenda', first).click()
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe('Project Phoenix kickoff agenda')
  await page.keyboard.press('ArrowLeft')
  await expect.poll(() => content.evaluate(element => element.editor.state.selection.empty
    && element.contains(document.activeElement) && window.getSelection()?.isCollapsed)).toBe(true)
  await page.keyboard.insertText('会议：')
  await expect.poll(highlighted).toBe('Project Phoenix kickoff agenda')
  await button('Project Phoenix kickoff agenda', first).click()
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe('Project Phoenix kickoff agenda')
  await content.press('ControlOrMeta+z')
  await expect(content.getByText('Project Phoenix kickoff agenda', { exact: true })).toBeVisible()
  await button('保存点').click()
  await expect(editor.locator('.editor-statusbar')).toContainText('已保存', { timeout: 25000 })
  await expect.poll(highlighted).toBe('Project Phoenix kickoff agenda')
  await button('Project Phoenix kickoff agenda', first).click()
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe('Project Phoenix kickoff agenda')
  await expect.poll(async () => {
    const boxes = await cards.evaluateAll(elements => elements.map(element => element.getBoundingClientRect()).sort((a, b) => a.top - b.top))
    return boxes.every((box, i) => i === 0 || box.top >= boxes[i - 1].bottom + 10)
  }).toBe(true)
  await expect(comments.locator('.word-review-tethers path')).toHaveAttribute('d', /^M /)
  assert.equal(await comments.evaluate(element => getComputedStyle(element).overflowY), 'visible', 'comments have no independent scrolling list')
  const before = { mark: await mark.boundingBox(), card: await first.boundingBox() }
  await viewport.evaluate(element => { element.scrollTop += 120 })
  await expect.poll(async () => Math.abs((await first.boundingBox()).y - before.card.y)).toBeGreaterThan(50)
  const after = { mark: await mark.boundingBox(), card: await first.boundingBox() }
  assert(Math.abs((after.mark.y - before.mark.y) - (after.card.y - before.card.y)) < 2, 'text and card scroll together')
  await button('Project Phoenix kickoff agenda', first).click()
  await page.screenshot({ path: join(output, 'word-margin.png') })

  await button('放大文档').click()
  await button('放大文档').click()
  await expect(viewport).toHaveAttribute('data-canvas-zoom', '1.2')
  await expect(comments).toHaveAttribute('data-compact', 'false')
  await expect(mark).toHaveClass(/is-active/)
  const firstBox = await first.boundingBox(), pageBox = await editor.locator('main.document').boundingBox()
  assert(firstBox.x > pageBox.x + pageBox.width, 'zoom keeps comments outside the paper')
  await button('重置文档缩放').click()

  const revision = (await editor.locator('.editor-statusbar').innerText()).match(/r\d+/)?.[0]
  await page.setViewportSize({ width: 900, height: 900 })
  await expect(comments).toHaveAttribute('data-compact', 'true')
  await expect(first).toBeVisible()
  await expect(first).toBeInViewport()
  await expect(second).not.toBeVisible()
  await button('下一条批注', comments).click()
  await expect(second).toHaveAttribute('data-active', 'true')
  await expect(second).toBeVisible()
  await expect(second).toBeInViewport()
  await expect(comments.getByRole('heading', { name: '批注', exact: true })).toBeInViewport()
  await expect(first).not.toBeVisible()
  await button('回复', second).click()
  await expect(comments.getByRole('textbox', { name: '回复内容' })).toBeFocused()
  await button('取消', second).click()
  const box = await second.boundingBox(), view = await viewport.boundingBox()
  assert(box.x >= view.x && box.x + box.width <= view.x + view.width + 1, 'active thread stays inside the narrow canvas')
  await expect(editor.locator('.editor-statusbar')).toContainText(revision)
  await page.screenshot({ path: join(output, 'word-margin-compact.png') })
  await page.setViewportSize(originalViewport)
  await expect(comments).toHaveAttribute('data-compact', 'false')
  await expect(first).toBeVisible()
  await page.reload()
  await expect(content).toHaveAttribute('contenteditable', 'true', { timeout: 45000 })
  await button('审阅').click()
  await expect(cards).toHaveCount(3)
  await expect.poll(() => content.locator('[data-word-comment-id]').evaluateAll(elements => new Set(elements.map(element => element.dataset.wordCommentId)).size)).toBe(3)
  await expect(comments.getByText('请补充这次启动会的负责人。', { exact: true })).toBeVisible()
  checks.push('Word page-margin comments share the paper scroll surface, highlight both nearby anchors, avoid card collisions, keep tethers under zoom, use an active thread in a narrow canvas, and restore all threads after refresh without adding a document revision.')
}
