import assert from 'node:assert/strict'
import { copyFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { expect } from '../editor/node_modules/@playwright/test/index.mjs'
const fixtures = resolve(import.meta.dirname, 'fixtures/native-office')

export async function verifyImageLayers(page, proof, checks) {
  for (const name of ['素材原件.png', '橙色卡片.png', '蓝色卡片.png']) copyFileSync(join(fixtures, name), join(proof, name))
  const ctx = page.context(), states = new Map(), raster = new Map(), requests = []
  const note = detail => checks.push(detail)
  page.on('response', response => {
    if (!response.ok()) return
    const url = new URL(response.url())
    if (url.pathname.endsWith('/image') && response.request().method() === 'GET') void response.json().then(info => states.set(info.revision, info)).catch(() => {})
    if (url.pathname.endsWith('/image/content')) {
      const rev = url.searchParams.get('revision')
      if (rev !== null) raster.set(+rev, response.body().catch(() => null))
    }
    if (url.pathname.endsWith('/node-patch') && response.request().postDataJSON()?.schemaVersion === 'hcd-patch/63') requests.push(response.request())
  })
  const home=page.getByRole('tab',{name:'首页',exact:true})
  const editor=page.locator('.desk-editor.is-visible')
  const layerList=editor.getByRole('list',{name:'图层列表',exact:true})
  const toolbar=editor.getByRole('navigation',{name:'图片工具',exact:true})
  const layers=()=>toolbar.getByRole('button',{name:'图层',exact:true}).click()
  const layerNames=()=>layerList.locator('strong').allTextContents()
  const revision=async value=>{
    await expect(editor.getByRole('complementary',{name:'图层',exact:true}).getByText(`图层随版本保存 · r${value}`,{exact:true})).toBeVisible({timeout:25000})
    await expect.poll(()=>states.has(value),{timeout:25000}).toBe(true)
    return states.get(value).imageLayers.stack
  }
  async function upload(name) {
    await home.click()
    await page.locator('.desk-home-main input[type=file]').setInputFiles(join(proof,name))
    await expect(page.getByRole('tab',{name,exact:true})).toHaveAttribute('aria-selected','true',{timeout:45000})
    await expect(editor.locator('.image-pixels')).toHaveJSProperty('width',768,{timeout:25000})
  }
  async function asset(name) {
    const chooser=page.waitForEvent('filechooser')
    await editor.getByRole('button',{name:'导入图层',exact:true}).click()
    await (await chooser).setFiles(join(proof,name))
  }
  async function value(label,value) {
    const control=editor.getByLabel(label,{exact:true})
    await control.fill(String(value)); await control.press('Enter')
  }
  async function saveRaster(rev,name) {
    await expect.poll(()=>raster.has(rev)).toBe(true)
    const bytes=await raster.get(rev)
    assert(bytes?.length>100)
    writeFileSync(join(proof,name),bytes)
  }
  async function download(format,name) {
    const controls=editor.locator('.export-control')
    const actions=editor.locator('summary[aria-label="文件操作"]')
    if (!(await controls.locator('summary').isVisible())) await actions.click()
    if (!(await controls.getByLabel('导出格式',{exact:true}).isVisible())) await controls.locator('summary').click()
    await controls.getByLabel('导出格式',{exact:true}).selectOption(format)
    await controls.getByRole('button',{name:'准备下载',exact:true}).click()
    const transfer=page.waitForEvent('download')
    await controls.getByRole('link',{name:new RegExp(`下载 .*\\.${format}$`)}).click({timeout:30000})
    await (await transfer).saveAs(join(proof,name))
  }
  async function moveArea(selector,dx,dy) {
    const point=await selector.boundingBox()
    assert(point && point.width>3 && point.height>3)
    const x=point.x+point.width*.5,y=point.y+point.height*.5
    const input=await ctx.newCDPSession(page)
    await input.send('Input.dispatchMouseEvent',{type:'mouseMoved',x,y,button:'none'})
    await input.send('Input.dispatchMouseEvent',{type:'mousePressed',x,y,button:'left',buttons:1,clickCount:1})
    await input.send('Input.dispatchMouseEvent',{type:'mouseMoved',x:x+dx,y:y+dy,button:'left',buttons:1})
    await input.send('Input.dispatchMouseEvent',{type:'mouseReleased',x:x+dx,y:y+dy,button:'left',clickCount:1})
    await input.detach()
  }
  await upload('素材原件.png')
  await layers()
  await expect(layerList).toBeVisible()
  assert.deepEqual(await layerNames(),['原图'])
  await asset('橙色卡片.png')
  const first=await revision(1)
  assert.deepEqual(first.layers.map(layer=>layer.name),['原图','橙色卡片'])
  await value('图层名称','橙色贴纸'); await revision(2)
  const outline=editor.getByRole('group',{name:'移动图层 橙色贴纸',exact:true})
  await expect(outline).toBeVisible()
  await moveArea(outline,58,31)
  const moved=await revision(3)
  assert(moved.layers[1].x>first.layers[1].x+10 && moved.layers[1].y>first.layers[1].y+10)
  await moveArea(editor.getByRole('button',{name:'调整图层大小 橙色贴纸'}),28,23)
  const resized=await revision(4)
  assert(resized.layers[1].width>moved.layers[1].width && resized.layers[1].height>moved.layers[1].height)
  await value('不透明度 %',56)
  const opacity=await revision(5)
  assert.equal(opacity.layers[1].opacity,56)
  await asset('蓝色卡片.png')
  const added=await revision(6)
  assert.deepEqual(added.layers.map(layer=>layer.name),['原图','橙色贴纸','蓝色卡片'])
  await saveRaster(6,'before-sort.png')
  const rows=layerList.locator('li')
  await rows.filter({hasText:'蓝色卡片'}).dragTo(rows.filter({hasText:'橙色贴纸'}))
  const sorted=await revision(7)
  assert.deepEqual(sorted.layers.map(layer=>layer.name),['原图','蓝色卡片','橙色贴纸'])
  await saveRaster(7,'after-sort.png')
  await editor.getByRole('button',{name:'隐藏图层 橙色贴纸',exact:true}).click()
  const hidden=await revision(8)
  assert(!hidden.layers[2].visible)
  await saveRaster(8,'hidden-layer.png')
  await editor.getByRole('button',{name:'显示图层 橙色贴纸',exact:true}).click()
  await revision(9)
  await saveRaster(9,'working-composite.png')
  note('Workbench imported layers, moved and resized on-canvas, renamed, set opacity, drag-sorted and toggled visibility with saved revisions.')
  const former=requests[3], headers=await former.allHeaders(), historical=former.postDataJSON()
  const failed=await ctx.request.post(former.url(),{headers:{authorization:headers.authorization,'x-hcd-protocol-fingerprint':headers['x-hcd-protocol-fingerprint'],'x-hcd-collaboration-epoch':headers['x-hcd-collaboration-epoch']||'0','content-type':'application/json'},data:{...historical,patchId:'stale-workbench-test'}})
  assert([409,412].includes(failed.status()),`stale mutation HTTP ${failed.status()}`)
  note(`A concurrent stale layer mutation was rejected with HTTP ${failed.status()}.`)
  await page.reload()
  await expect(toolbar.getByRole('button',{name:'图层',exact:true})).toBeEnabled({timeout:45000})
  await layers()
  await revision(9)
  assert.deepEqual(await layerNames(),['橙色贴纸','蓝色卡片','原图'])
  await expect(editor.getByLabel('不透明度 %',{exact:true})).toHaveValue('56')
  await page.screenshot({path:join(proof,'layers-workbench.png')})
  await toolbar.getByRole('button',{name:'光线与色彩',exact:true}).click()
  await editor.getByRole('slider',{name:'曝光',exact:true}).fill('14')
  await editor.getByRole('button',{name:'应用编辑',exact:true}).click()
  await expect.poll(()=>states.has(10),{timeout:25000}).toBe(true)
  await layers()
  const adjusted=await revision(10)
  assert.equal(adjusted.layers.at(-1).name,'调整结果')
  assert.equal(adjusted.layers.at(-1).blend,'replace')
  assert.deepEqual(adjusted.layers.slice(0,-1),states.get(9).imageLayers.stack.layers)
  await saveRaster(10,'adjustment-layer.png')
  await editor.getByRole('button',{name:'隐藏图层 调整结果',exact:true}).click()
  await revision(11)
  await saveRaster(11,'adjustment-hidden.png')
  note('Reload restored the layer selection and properties; a color adjustment saved as a reversible result layer.')
  await download('png','composite-reopened.png')
  await download('hcd','editable-layers.hcd')
  await layers()
  await editor.getByRole('button',{name:'图层版本记录',exact:true}).click()
  await editor.getByRole('button',{name:/版本 r6/}).click()
  await editor.getByRole('button',{name:'恢复此版本',exact:true}).click()
  await expect.poll(()=>states.has(12),{timeout:25000}).toBe(true)
  await layers()
  assert.deepEqual(await revision(12),added)
  await saveRaster(12,'restored-layer-order.png')
  note('Restoring a prior revision restored its layer order, metadata and raster together.')
  await upload('composite-reopened.png')
  await layers()
  await revision(0)
  assert.deepEqual(await layerNames(),['原图'])
  await saveRaster(0,'readback-png.png')
  note('Downloaded the current composition in its original PNG format and reopened it as a new raster document; also downloaded the layer archive.')
  writeFileSync(join(proof, 'browser-verification.json'), JSON.stringify({ checks, states: [...states], writeCount: requests.length }, null, 2))
}
