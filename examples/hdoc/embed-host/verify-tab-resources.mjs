import assert from 'node:assert/strict'
import { expect } from '../editor/node_modules/@playwright/test/index.mjs'

export async function verifyTabResources(page, checks) {
  const doc = '工作坊简报.docx', board = '共创工作坊.excalidraw'
  const csv = '区域进展.csv', tsv = '回访结果.tsv'
  const pane = page.locator('.desk-editor.is-visible')
  const home = page.getByRole('tab', {name: '首页', exact: true})
  const tab = name => page.getByRole('tab', {name, exact: true}).click()
  const prompt = page.getByRole('textbox', {name: '全局 AI 指令'})
  const target = name => page.getByRole('checkbox', {name: '加入任务 ' + name, exact: true})
  const scope = name => page.locator('.desk-targets label').filter({has: target(name)})
  const open = async name => { await home.click(); await page.getByRole('button', {name: '打开 ' + name, exact: true}).click() }
  const reopen = async name => {
    await page.getByRole('button', {name: '管理标签', exact: true}).click()
    await page.locator('.desk-tab-menu').getByRole('button', {name, exact: true}).click()
  }
  const close = async name => {
    await page.getByRole('button', {name: '关闭 ' + name, exact: true}).click()
    await expect(page.getByRole('tab', {name, exact: true})).toHaveCount(0)
  }
  const read = async (name, route, request) => page.evaluate(async ({name, route, request}) => {
    const {files} = await (await fetch('/workspace/api/files')).json()
    const file = files.find(f => f.name === name)
    const {csrf} = await (await fetch('/workspace/api/session')).json()
    const launch = await (await fetch('/workspace/api/files/' + file.id + '/editor-session', {method: 'POST',
      headers: {'Content-Type':'application/json', 'X-Workspace-CSRF':csrf}, body:JSON.stringify({sessionId:crypto.randomUUID()})})).json()
    const result = await fetch('/v1/documents/' + file.resourceDocumentId + route, {
      method: request?.method || 'GET',
      headers:{Authorization:'Bearer ' + launch.token, ...(request?.body && {'Content-Type':'application/json'})},
      body: request?.body ? JSON.stringify({...request.body, documentId: file.resourceDocumentId}) : undefined,
    })
    if (!result.ok) throw Error(await result.text())
    return result.json()
  }, {name, route, request})
  for (const [name, type, content] of [[csv,'text/csv','区域,本周,上周\n华东,108,90\n华南,99,110\n'], [tsv,'text/tab-separated-values','区域\t备注\n华东\t待核对\n']]) {
    await home.click()
    const fileInput = page.locator('.desk-home input[type=file]')
    await expect(fileInput).toHaveAttribute('accept', new RegExp('\\.' + name.split('.').pop()))
    const uploaded = page.waitForResponse(r => new URL(r.url()).pathname === '/workspace/api/files' && r.request().method() === 'POST')
    await fileInput.setInputFiles({name, mimeType:type, buffer:Buffer.from(content)})
    assert.equal((await uploaded).status(), 201)
    await expect(pane.locator('.hcd-univer-host')).toBeVisible({timeout:45000})
    await expect(target(name)).toBeEnabled({timeout:45000})
    assert((await read(name, '/sheets/0')).cells.some(c => c.text === '华东'))
  }
  checks.push('CSV and TSV uploaded through Home, opened in editable workbook tabs, and returned original cells from the engine.')
  const blankValue = '临时的 AI 批注'
  const sheetCanvas = pane.locator('canvas[id^="univer-sheet-main-canvas_"]').first()
  await sheetCanvas.click({position:{x:58,y:32}})
  const address = pane.getByLabel('选中单元格',{exact:true})
  await expect(address).toHaveText('A1')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  await expect(address).toHaveText('C1')
  for (const checkbox of await page.getByRole('checkbox',{name:/^加入任务 /}).all()) await checkbox.uncheck()
  await target(tsv).check()
  await expect(scope(tsv)).toContainText('C1')
  await prompt.fill('写入：' + blankValue)
  await page.getByRole('button',{name:'发送全局指令',exact:true}).click()
  const fill = page.locator('.desk-thread article').filter({has:page.locator('.desk-user-message',{hasText:blankValue})})
  await fill.getByRole('button',{name:'应用到 ' + tsv,exact:true}).click()
  await expect(fill.locator('em[data-phase="complete"]')).toHaveCount(1,{timeout:45000})
  const written = await read(tsv,'/sheets/0')
  const addedCell = written.cells.find(cell => cell.address === 'C1')
  assert.equal(addedCell?.text, blankValue)
  const untouched = written.cells.find(cell => cell.address === 'B2')
  await read(tsv,'/node-patch',{method:'POST',body:{schemaVersion:'hcd-patch/1',patchId:crypto.randomUUID(),baseRevision:written.revision,
    operations:[{op:'text.splice', nodeId:untouched.nodeId, start:0, deleteCount:[...untouched.text].length,
      insertText:'同事已核对', precondition:{nodeHash:untouched.nodeHash}}]}})
  await page.reload()
  await expect(fill.locator('em[data-phase="complete"]')).toHaveCount(1,{timeout:45000})
  await fill.getByRole('button',{name:/撤销 回访结果\.tsv r\d+ 的修改/}).click()
  await expect(fill.getByText('已撤销',{exact:true})).toBeVisible({timeout:45000})
  const cleared = await read(tsv,'/sheets/0')
  assert(!cleared.cells.some(cell => cell.address === 'C1'))
  assert.equal(cleared.cells.find(cell => cell.address === 'B2').text, '同事已核对')
  checks.push('A reviewed AI first write to a blank TSV cell was undone after reload. Engine inspection confirms the cell is physically absent and a later edit to a different cell remains.')

  const files = await page.evaluate(async () => (await (await fetch('/workspace/api/files')).json()).files)
  const id = name => files.find(f => f.name === name).resourceDocumentId
  const wordDraft = '保留这一段的修改要求', sheetDraft = '核对这四个单元格', boardDraft = '整理这张引用卡'
  await open(doc)
  const paragraph = pane.locator('.tiptap p').filter({hasText:'可以验证的假设'}).first()
  const selectParagraph = async () => {
    await expect(pane.locator('.tiptap').first()).toHaveAttribute('contenteditable', 'true', {timeout:45000})
    await paragraph.scrollIntoViewIfNeeded()
    const points = await paragraph.evaluate(p => {
      const range = document.createRange()
      range.selectNodeContents(p)
      const rects = Array.from(range.getClientRects()).filter(rect => rect.width > 2 && rect.height > 2)
      const first = rects[0], last = rects.at(-1)
      return {x:Math.ceil(first.left) + 2, y:first.top + first.height / 2, endX:Math.floor(last.right) - 1, endY:last.top + last.height / 2}
    })
    await page.mouse.move(points.x, points.y)
    await page.mouse.down()
    await page.mouse.move(points.endX, points.endY, {steps: 15})
    await page.mouse.up()
    await expect(pane.locator('.tiptap').first()).toBeFocused()
    await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toContain('可以验证的假设')
    return points
  }
  await selectParagraph()
  await expect(scope(doc)).toContainText('正文')
  await target(doc).check()
  await prompt.fill(wordDraft)
  await open(board)
  await expect(pane.getByRole('button',{name:'插入资源',exact:true})).toBeVisible({timeout:45000})
  async function insert(name, range, presentation) {
    await pane.getByRole('button',{name:'插入资源',exact:true}).click()
    const dialog = page.getByRole('dialog',{name:'插入资源引用'})
    await dialog.getByLabel('引用源文件').selectOption(id(name))
    if (range) {
      await expect(dialog.getByLabel('引用工作表').locator('option')).not.toHaveCount(0)
      await dialog.getByLabel('引用表格区域').fill(range)
      if (presentation) await dialog.getByLabel('呈现方式').selectOption(presentation)
    } else {
      const block = dialog.getByLabel('引用段落').locator('option').filter({hasText:'可以验证的假设'}).first()
      await expect(block).toBeAttached()
      await expect(dialog.getByLabel('引用段落')).toHaveValue(await block.getAttribute('value'))
    }
    await dialog.getByRole('button',{name:'插入白板'}).click()
    await expect(dialog).toBeHidden()
    const card = pane.locator('.resource-card[data-resource-document="' + id(name) + '"]').last()
    if (presentation) await expect(card.locator('[data-value="108"]')).toHaveCount(1, {timeout:30000})
    else await expect(card).toContainText(range ? '108' : '可以验证的假设', {timeout:30000})
    const rect = await card.boundingBox()
    await page.mouse.move(rect.x + 25, rect.y + 18)
    await expect(pane.getByRole('toolbar',{name:'引用操作'})).toHaveAttribute('data-owner', await card.getAttribute('data-resource-element'))
    await expect(pane.getByRole('button',{name:'进入引用源文件',exact:true})).toBeVisible()
    return card
  }
  await insert(doc)
  await close(doc)
  await pane.getByRole('button',{name:'进入引用源文件',exact:true}).click()
  await expect(page.getByRole('tab',{name:doc,exact:true})).toHaveAttribute('aria-selected','true')
  await expect(scope(doc)).toContainText('正文',{timeout:45000})
  await expect(prompt).toHaveValue(wordDraft)
  await page.getByRole('button',{name:'返回白板',exact:true}).click()
  const sheetCard = await insert(csv,'B2:C3')
  await expect(sheetCard.locator('tbody tr')).toHaveCount(2)
  await pane.getByRole('button',{name:'AI 编辑源内容',exact:true}).click()
  await expect(scope(csv)).toContainText('B2:C3',{timeout:45000})
  await expect(target(csv)).toBeChecked()
  await expect(target(doc)).not.toBeChecked()
  await prompt.fill(sheetDraft)
  await page.getByRole('button',{name:'返回白板',exact:true}).click()
  await expect(scope(board)).toContainText('选中 1 个对象')
  await target(board).check()
  await prompt.fill(boardDraft)
  await page.reload()
  for (const [name, draft, label] of [[board,boardDraft,'选中 1 个对象'],[csv,sheetDraft,'B2:C3'],[doc,wordDraft,'正文']]) {
    await tab(name)
    await expect(prompt).toHaveValue(draft)
    await expect(scope(name)).toContainText(label,{timeout:45000})
    await expect(target(name)).toBeChecked()
    await close(name); await reopen(name)
    await expect(prompt).toHaveValue(draft)
    await expect(scope(name)).toContainText(label,{timeout:45000})
    await expect(target(name)).toBeChecked()
  }
  checks.push('Word, CSV and canvas each restored their distinct unsent prompt, selected range/object and task file after switching, reload and reopening a closed tab.')
  await tab(board)
  await pane.getByRole('button',{name:'整理为文档',exact:true}).click()
  const dialog = page.getByRole('dialog',{name:'整理为文档'})
  await expect(dialog.getByLabel('写入预览')).toContainText('108')
  await dialog.getByLabel('整理目标文档').selectOption(id(doc))
  await expect(dialog.getByLabel('写入预览').getByRole('table').getByRole('cell', {name:'108'})).toBeVisible()
  await dialog.getByRole('button',{name:'写入文档'}).click()
  await expect(dialog.getByRole('status')).toContainText('已写入',{timeout:45000})
  await dialog.getByRole('button',{name:'查看文档'}).click()
  const inserted = pane.locator('.tiptap .hcd-opaque-preview iframe').first().contentFrame()
  await expect(inserted.getByRole('cell',{name:'108',exact:true})).toBeVisible({timeout:45000})
  const projection = await read(doc,'/editor')
  const blocks = projection.blocks
  const table = blocks.find(b => b.readOnlyHtml?.includes('hcd-editor-table') && b.content.inlines.some(i => i.text === '108'))
  assert.deepEqual(table?.content.inlines.map(i => i.text), ['108','90','99','110'])
  assert.equal(table.editableTextNodeIds.length,4)
  const backlink = blocks.flatMap(b => b.content.inlines).find(i => i.text === '查看白板来源' && i.link?.includes('node-id='))
  assert(backlink)
  await page.reload()
  await expect(inserted.getByRole('cell',{name:'108',exact:true})).toBeVisible({timeout:45000})
  await expect(prompt).toHaveValue(wordDraft)
  await expect(page.getByRole('button',{name:'发送全局指令'})).toBeDisabled()
  await expect(page.getByRole('button',{name:'使用当前文件和选区'})).toBeVisible()
  const origin = await page.context().newPage()
  try {
    await origin.goto(backlink.link)
    await expect(origin.getByRole('tab',{name:board,exact:true})).toHaveAttribute('aria-selected','true')
    await expect(origin.locator('.desk-editor.is-visible').getByRole('button',{name:'进入引用源文件',exact:true})).toBeVisible({timeout:45000})
  } finally { await origin.close() }
  checks.push('Word and CSV reference cards survived reload. A board selection wrote four editable Word cells and a working backlink in one revision.')
  async function confirmSourceReference(name, range) {
    const choice = page.getByRole('dialog', {name: '选择目标白板'})
    await choice.getByLabel('目标白板').selectOption(id(board))
    await choice.getByRole('button', {name: '继续'}).click()
    const picker = page.getByRole('dialog', {name: '插入资源引用'})
    await expect(picker.getByLabel('引用源文件')).toHaveValue(id(name))
    if (range) await expect(picker.getByLabel('引用表格区域')).toHaveValue(range)
    else await expect(picker.getByLabel('引用段落').locator('option:checked')).toContainText('可以验证的假设')
    const cards = pane.locator('.resource-card[data-resource-document="' + id(name) + '"]')
    const before = await cards.count()
    await picker.getByRole('button', {name: '插入白板'}).click()
    await expect(picker).toBeHidden()
    await expect(cards).toHaveCount(before + 1)
  }
  await paragraph.click({button:'right', position:{x:35,y:10}})
  await page.getByRole('menuitem',{name:'引用段落到白板'}).click()
  await confirmSourceReference(doc)
  await tab(csv)
  await pane.getByRole('button',{name:'插入',exact:true}).click()
  const expand = pane.getByRole('button',{name:'展开工具栏',exact:true})
  if (await expand.isVisible()) await expand.click()
  await pane.getByRole('button',{name:'引用区域到白板'}).click()
  await confirmSourceReference(csv,'B2:C3')
  checks.push('Both source editors placed their actual paragraph or B2:C3 selection on the chosen board without retyping its address.')

  const chart = await insert(csv, 'B2:C3', 'bar')
  const chartId = await chart.getAttribute('data-resource-element')
  const before = await read(csv,'/sheets/0')
  await read(csv, '/node-patch', {method:'POST', body:{schemaVersion:'hcd-patch/12', patchId:crypto.randomUUID(),
    baseRevision:before.revision, operations:[{op:'xlsx.row.insert',sheetId:before.sheetId,beforeRow:2}]}})
  const firstValue = before.cells.find(cell => cell.address === 'B2')
  const moved = await read(csv,'/sheets/0')
  assert.equal(moved.cells.find(cell => cell.nodeId === firstValue.nodeId).address,'B3')
  await expect(chart).toHaveAttribute('aria-label', /B3:C4/, {timeout:25000})
  await expect(chart.locator('rect[data-value="108"]')).toHaveCount(1)
  await pane.getByRole('button',{name:'进入引用源文件',exact:true}).click()
  const location = page.getByRole('region',{name:'资源引用定位'})
  await expect(location).toContainText('B3:C4')
  await expect(location.getByRole('status')).toHaveText('已进入源文件')
  await expect(pane.getByLabel('选中单元格',{exact:true})).toHaveText('B3')
  const field = pane.getByRole('textbox',{name:'单元格内容或公式',exact:true})
  await expect(field).toHaveValue('108')
  await field.fill('121')
  await expect(pane.getByLabel('未应用输入位置')).toContainText('B3')
  const savedCell = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname.endsWith('/node-patch'), {timeout:6000}).catch(() => null)
  await pane.getByRole('button',{name:'应用内容',exact:true}).click()
  const applied = await savedCell
  assert(applied, 'No cell patch was sent: ' + (await pane.innerText()).slice(-1100))
  assert(applied.ok(), await applied.text())
  await expect.poll(async () => (await read(csv,'/sheets/0')).cells.find(cell => cell.nodeId === firstValue.nodeId)?.text).toBe('121')
  await page.getByRole('button',{name:'返回白板',exact:true}).click()
  const identifiedChart = pane.locator(`[data-resource-element="${chartId}"]`)
  await expect(identifiedChart.locator('rect[data-value="121"]')).toHaveCount(1,{timeout:25000})
  await expect(identifiedChart.locator('rect[data-value="108"]')).toHaveCount(0)
  const pos = await identifiedChart.boundingBox()
  await page.mouse.move(pos.x + 22, pos.y + 17)
  await pane.getByLabel('引用呈现方式').selectOption('line')
  await expect.poll(async () => (await read(board, '/canvas')).scene.elements.find(item => item.id === chartId)?.customData?.officeResource?.presentation).toBe('line')
  await expect(identifiedChart.locator('circle[data-value="121"]')).toHaveCount(1,{timeout:25000})
  const beforeColumn = await read(csv, '/sheets/0')
  await read(csv, '/node-patch', {method:'POST', body:{schemaVersion:'hcd-patch/13', patchId:crypto.randomUUID(),
    baseRevision:beforeColumn.revision, operations:[{op:'xlsx.column.insert',sheetId:beforeColumn.sheetId,beforeColumn:2}]}})
  const columnMoved = await read(csv, '/sheets/0')
  assert.equal(columnMoved.cells.find(cell => cell.nodeId === firstValue.nodeId).address, 'C3')
  await expect(identifiedChart.locator('figure')).toHaveAttribute('aria-label', /C3:D4/, {timeout:25000})
  await expect(identifiedChart.locator('circle[data-value="121"]')).toHaveCount(1)
  checks.push('Row and column insertion moved the linked chart from B2:C3 to B3:C4 and C3:D4. The real source edit updated the bar chart, and its line-chart view retained the same board object.')

  const oldBoard = await read(board,'/canvas')
  await tab(doc)
  const points = await selectParagraph()
  await page.mouse.click(points.x + 12, points.y, {button:'right'})
  await page.getByRole('menuitem',{name:'在白板讲解',exact:true}).click()
  const explain = page.getByRole('dialog',{name:'在白板讲解',exact:true})
  await expect(explain.getByLabel('目标文件')).toHaveValue(id(board))
  await explain.getByRole('button',{name:'生成预览'}).click()
  await expect(explain.getByLabel('生成预览')).toContainText('工作坊讲解图',{timeout:45000})
  assert.equal((await read(board,'/canvas')).revision,oldBoard.revision)
  await explain.getByRole('button',{name:'追加到白板'}).click()
  await expect(explain.getByRole('status')).toContainText('已应用')
  await explain.getByRole('button',{name:'查看结果'}).click()
  await expect(page.getByRole('tab',{name:board,exact:true})).toHaveAttribute('aria-selected','true')
  const updated = await read(board,'/canvas')
  const oldIds = new Set(oldBoard.scene.elements.map(element => element.id))
  const created = updated.scene.elements.filter(element => !oldIds.has(element.id))
  assert(created.some(element => element.type === 'text' && element.text.includes('提炼假设')))
  assert(created.some(element => element.type === 'arrow'))
  assert.deepEqual(updated.scene.elements.filter(element => oldIds.has(element.id)), oldBoard.scene.elements)
  await pane.getByRole('button',{name:'查看原文',exact:true}).click()
  await expect(page.getByRole('tab',{name:doc,exact:true})).toHaveAttribute('aria-selected','true')
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toContain('可以验证的假设')
  checks.push('A hosted Word selection generated a preview with a loopback model, appended editable diagram elements, left existing objects in place and returned to the original selected passage.')
}
